import { roles } from '../data/players.js'
import { defaultStatus, experienceOptions, recruitment } from '../data/recruitment.js'

export const emptyValues = {
  pubgUsername: '', pubgId: '', age: '', country: '', role: '', kd: '', experience: '',
  previousClan: '', discord: '', additional: '', consent: false,
  website: '', // honeypot: real people never see or fill this
}

// Order used for focusing the first invalid field.
export const fieldOrder = ['pubgUsername', 'pubgId', 'age', 'country', 'role', 'kd', 'experience', 'previousClan', 'discord', 'additional', 'consent']

const t = (v) => String(v ?? '').trim()
export const normalizeDiscord = (v) => t(v).replace(/^@/, '').toLowerCase()
export const normalizeKd = (v) => t(v).replace(',', '.')

/**
 * One validator per field. Each returns an error message, or '' when valid.
 * ID/username formats are deliberately lenient; tighten them here if your
 * platform has a fixed format.
 */
export const validators = {
  pubgUsername(v) {
    v = t(v)
    if (!v) return 'Enter your PUBG username.'
    if (v.length < 3 || v.length > 30) return 'Username must be 3 to 30 characters.'
    if (/\s/.test(v)) return 'Usernames cannot contain spaces.'
    return ''
  },
  pubgId(v) {
    v = t(v)
    if (!v) return 'Enter your PUBG ID.'
    if (v.length < 5 || v.length > 40) return 'PUBG ID must be 5 to 40 characters.'
    if (!/^[A-Za-z0-9._-]+$/.test(v)) return 'PUBG ID can only contain letters, numbers, dots, hyphens and underscores.'
    return ''
  },
  age(v) {
    v = t(v)
    if (!v) return 'Enter your age.'
    if (!/^\d{1,3}$/.test(v)) return 'Enter your age as a whole number.'
    const n = Number(v)
    if (n > 99) return 'Enter a valid age.'
    if (n < recruitment.minAge) return `You must be at least ${recruitment.minAge} years old to apply.`
    return ''
  },
  country(v) {
    v = t(v)
    if (!v) return 'Enter your country.'
    if (v.length < 2 || v.length > 56) return 'Country must be 2 to 56 characters.'
    if (!/^[\p{L}\s.'’()-]+$/u.test(v)) return 'Enter a valid country name.'
    return ''
  },
  role(v) {
    if (!v) return 'Select your preferred in-game role.'
    return roles[v] ? '' : 'Select one of the listed roles.'
  },
  kd(v) {
    v = normalizeKd(v)
    if (!v) return 'Enter your K/D ratio.'
    if (!/^\d{1,2}(\.\d{1,2})?$/.test(v)) return 'Enter your K/D as a number, for example 3.45.'
    const n = Number(v)
    if (n <= 0) return 'K/D ratio must be greater than 0.'
    if (n > 50) return 'That K/D looks too high. Please check it.'
    return ''
  },
  experience(v) {
    if (!v) return 'Select your competitive experience.'
    return experienceOptions.some((o) => o.value === v) ? '' : 'Select one of the listed options.'
  },
  previousClan(v) {
    return t(v).length > 60 ? 'Keep this under 60 characters.' : ''
  },
  discord(v) {
    v = normalizeDiscord(v)
    if (!v) return 'Enter your Discord username.'
    const modern = /^(?!.*\.\.)[a-z0-9_.]{2,32}$/.test(v)
    const legacy = /^.{2,32}#\d{4}$/.test(v)
    return modern || legacy ? '' : 'Enter a valid Discord username, for example onslaught_player.'
  },
  additional(v) {
    return t(v).length > 1000 ? 'Keep this under 1000 characters.' : ''
  },
  consent(v) {
    return v ? '' : 'Please confirm to submit your application.'
  },
}

export const validateField = (name, value) => validators[name]?.(value) ?? ''

export function validateAll(values) {
  const errors = {}
  for (const name of Object.keys(validators)) {
    const message = validators[name](values[name])
    if (message) errors[name] = message
  }
  return errors
}

/**
 * Clean, database-ready row (snake_case, typed). This matches the columns in
 * supabase/applications.sql. `id` and `created_at` are generated by the database.
 */
export function toApplicationRecord(values) {
  return {
    pubg_username: t(values.pubgUsername),
    pubg_id: t(values.pubgId),
    age: Number(t(values.age)),
    country: t(values.country),
    preferred_role: values.role,
    kd_ratio: Number(normalizeKd(values.kd)),
    competitive_experience: values.experience,
    previous_clan: t(values.previousClan) || null,
    discord_username: normalizeDiscord(values.discord),
    additional_info: t(values.additional) || null,
    status: defaultStatus,
  }
}

// Remembers a *saved* application in this browser to prevent accidental repeats.
// The database unique constraint on pubg_id is the real duplicate guard.
const KEY = 'ons.recruitment.application.v1'
export const readSubmission = () => { try { return JSON.parse(localStorage.getItem(KEY)) } catch { return null } }
export const saveSubmission = (data) => { try { localStorage.setItem(KEY, JSON.stringify(data)) } catch { /* storage unavailable */ } }
export const clearSubmission = () => { try { localStorage.removeItem(KEY) } catch { /* storage unavailable */ } }
